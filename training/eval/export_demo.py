"""Export recorded evaluation aggregates for the comparison UI. Never exports corpus text.

    backend/.venv/bin/python training/eval/export_demo.py
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RESULTS = ROOT / "training/eval/results"
DEST = ROOT / "frontend/src/app/core/evaluation-results.ts"


def export() -> None:
    summary = json.loads((RESULTS / "summary.json").read_text())
    rows = []
    for name, label in (("base-short", "Standard · one-line prompt"),
                        ("base-full", "Standard · app prompt"),
                        ("tuned-short", "Fine-tuned v2 · one-line prompt")):
        raw = [json.loads(line) for line in (RESULTS / f"{name}.jsonl").read_text().splitlines()]
        assert len(raw) == 120 and len({(r["id"], r["repeat"]) for r in raw}) == 120
        facts = [r for r in raw if r["category"] == "facts" and "correct" in r]
        memory = [r for r in raw if r["id"] == "turns-01"]
        s = summary[name]
        rows.append({"name": name, "label": label, "model": s["model"],
                     "promptTokens": s["avg_prompt_tokens"], "clean": s["clean_%"],
                     "tooLong": s["too_long_%"], "words": s["avg_words"],
                     "factsCorrect": sum(r["correct"] for r in facts), "factsTotal": len(facts),
                     "memoryCorrect": sum(r["correct"] for r in memory), "memoryTotal": len(memory)})
    DEST.write_text("// Generated by training/eval/export_demo.py from saved raw evaluation records.\n"
                    "export const EVALUATION_RESULTS = " + json.dumps(rows, indent=2) + " as const;\n")
    print(f"Wrote {DEST}")


if __name__ == "__main__":
    export()
